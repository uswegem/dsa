def get_or_create_branch(db, cache: dict, name: str) -> Branch:
    key = name.strip().upper()
    if key in cache:
        return cache[key]
    branch = db.query(Branch).filter(Branch.name.ilike(name.strip())).first()
    if branch is None:
        branch = Branch(name=name.strip().title())
        db.add(branch)
        db.flush()
        print(f"  + created branch: {branch.name}")
    cache[key] = branch
    return branch


def main():
    db = SessionLocal()
    branch_cache: dict[str, Branch] = {}
    dtl_cache: dict[tuple[str, str], Dtl] = {}  # (branch_key, name_key) -> Dtl

    try:
        print("=== Branches + DTLs ===")
        seq = 1
        for branch_name, dtl_name in DTL_ROWS:
            branch = get_or_create_branch(db, branch_cache, branch_name)
            name_key = dtl_name.strip().upper()
            dtl = (
                db.query(Dtl)
                .filter(Dtl.dtl_name.ilike(dtl_name.strip()), Dtl.branch_id == branch.id)
                .first()
            )
            if dtl is None:
                code = f"PENDING-{seq:03d}"
                seq += 1
                dtl = Dtl(dtl_code=code, dtl_name=dtl_name.strip(), branch_id=branch.id)
                db.add(dtl)
                db.flush()
                print(f"  + DTL {dtl.dtl_code}: {dtl.dtl_name} ({branch.name})")
            dtl_cache[(branch.id, name_key)] = dtl

        print("\n=== DSAs + assignments ===")
        created, updated, assigned = 0, 0, 0
        for line in DSA_TSV.strip("\n").splitlines():
            parts = line.split("\t")
            while len(parts) < 4:
                parts.append("")
            dsa_code, dsa_name, branch_name, dtl_name = (p.strip() for p in parts[:4])
            if not dsa_code or not dsa_name:
                print(f"  ! skipping malformed row: {line!r}")
                continue

            branch = get_or_create_branch(db, branch_cache, branch_name)

            dsa = db.query(Dsa).filter(Dsa.dsa_code == dsa_code).first()
            if dsa is None:
                dsa = Dsa(dsa_code=dsa_code, dsa_name=dsa_name, dsa_account_no=None, branch_id=branch.id)
                db.add(dsa)
                db.flush()
                created += 1
            else:
                dsa.dsa_name = dsa_name
                dsa.branch_id = branch.id
                updated += 1

            if dtl_name:
                dtl = dtl_cache.get((branch.id, dtl_name.strip().upper()))
                if dtl is None:
                    print(f"  ! no DTL record found for '{dtl_name}' in branch '{branch.name}' (DSA {dsa_code}) - skipping assignment")
                else:
                    sync_assignment(db, dsa, dtl, TODAY)
                    assigned += 1

        db.commit()
        print(f"\nDone. DSAs created: {created}, updated: {updated}, assignments set: {assigned}")
    finally:
        db.close()


if __name__ == "__main__":
    main()
